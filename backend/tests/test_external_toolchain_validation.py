def _find_exe(candidates: list[str], extra_globs: list[str] | None = None) -> Path | None:
    for name in candidates:
        found = shutil.which(name)
        if found:
            return Path(found)
    roots = [
        Path(os.environ.get("ProgramFiles", r"C:\Program Files")),
        Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")),
        Path(os.environ.get("LOCALAPPDATA", "")) / "Programs",
        Path(os.environ.get("LOCALAPPDATA", "")),
    ]
    for root in roots:
        if not root.exists():
            continue
        for pat in (extra_globs or []):
            for hit in root.glob(pat):
                if hit.is_file():
                    return hit
    return None


def test_arduino_cli_compiles_roboforge_uno_firmware(tmp_path: Path):
    """Autogenerated Arduino UNO + PCA9685 .ino must compile cleanly with real avr-gcc."""
    cli = _find_exe(
        ["arduino-cli", "arduino-cli.exe"],
        ["Arduino CLI/arduino-cli.exe", "arduino-cli/arduino-cli.exe"],
    )
    if cli is None:
        pytest.skip("arduino-cli not installed")

    poses = [
        {"name": "Home", "j0": 90, "j1": 90, "j2": 90, "j3": 90, "g": 45},
        {"name": "Pick", "j0": 45, "j1": 120, "j2": 60, "j3": 110, "g": 15},
        {"name": "Place", "j0": 135, "j1": 100, "j2": 75, "j3": 95, "g": 65},
    ]
    ino_code = generate_arduino_pca9685_ino("RoboForge_CI_Arm", poses, speed_ms=16)
    sketch_dir = tmp_path / "roboforge_uno"
    sketch_dir.mkdir(parents=True, exist_ok=True)
    (sketch_dir / "roboforge_uno.ino").write_text(ino_code, encoding="utf-8")

    proc = subprocess.run(
        [str(cli), "compile", "--fqbn", "arduino:avr:uno", str(sketch_dir)],
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert proc.returncode == 0, f"arduino-cli compile failed:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"


def test_mujoco_loads_and_steps_roboforge_exported_arm(tmp_path: Path):
    """Exported RoboForge MuJoCo XML must load cleanly in MuJoCo and step 250 stable physics frames."""
    mujoco = pytest.importorskip("mujoco")

    mats = load_materials()
    mat = mats["petg_cf"]
    req = ModularArmRequest(
        dof=6,
        payload_kg=1.0,
        material_id="petg_cf",
        joint_angles_deg=[15.0, -35.0, 25.0],
    )
    arm_req = ArmAssemblyRequest(
        preset="so_arm_lerobot",
        dof=6,
        payload_kg=1.0,
        material_id="petg_cf",
        joint_angles_deg=[15.0, -35.0, 25.0],
    )
    seg_vols = {"base": 65000.0, "upper_arm": 48000.0, "forearm": 36000.0, "wrist": 18000.0}
    eval_res = evaluate_arm_assembly(arm_req, seg_vols, mat)
    xml_path = export_topology_mujoco(req, eval_res, tmp_path / "roboforge_arm.xml")
    assert xml_path.exists() and xml_path.stat().st_size > 500

    model = mujoco.MjModel.from_xml_path(str(xml_path))
    data = mujoco.MjData(model)
    assert model.njnt >= 3, f"Expected >=3 joints in MuJoCo model, got {model.njnt}"

    for _ in range(250):
        mujoco.mj_step(model, data)

    assert np.all(np.isfinite(data.qpos)), "NaN/Inf in MuJoCo qpos"
    assert np.all(np.isfinite(data.qvel)), "NaN/Inf in MuJoCo qvel"


def test_freecad_imports_and_validates_roboforge_step_propeller(tmp_path: Path):
    """FreeCADCmd independently imports a RoboForge .STEP propeller and confirms B-Rep validity & volume."""
    fc = _find_exe(
        ["FreeCADCmd", "FreeCADCmd.exe", "freecadcmd.exe"],
        ["FreeCAD*/bin/FreeCADCmd.exe", "FreeCAD*/bin/freecadcmd.exe"],
    )
    if fc is None:
        pytest.skip("FreeCADCmd not installed")

    from build123d import export_step

    prop = generate_propeller_part(5.0, 4.3, 3, "naca4412", "conventional", "ccw")
    step_path = tmp_path / "roboforge_prop.step"
    export_step(prop, str(step_path))

    check_script = tmp_path / "check_step.py"
    check_script.write_text(
        "import Part\n"
        f"s = Part.read(r'{step_path}')\n"
        "assert s.isValid(), 'STEP shape invalid in FreeCAD'\n"
        "assert len(s.Solids) >= 1, f'Expected >=1 solid, got {len(s.Solids)}'\n"
        "assert s.Volume > 1500.0, f'Unexpected volume: {s.Volume}'\n"
        "print(f'FREECAD_OK solids={len(s.Solids)} vol={s.Volume:.1f}')\n",
        encoding="utf-8",
    )
    proc = subprocess.run(
        [str(fc), str(check_script)],
        capture_output=True,
        text=True,
        timeout=90,
    )
    assert proc.returncode == 0 and "FREECAD_OK" in proc.stdout, (
        f"FreeCAD validation failed:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )


def test_openscad_compiles_classic_link_vs_roboforge_simp3d(tmp_path: Path):
    """Real OpenSCAD CSG compiles a classic 180mm link STL and confirms RoboForge SIMP 3D saves >50% mass."""
    oscad = _find_exe(
        ["openscad", "openscad.com", "openscad.exe"],
        ["OpenSCAD/openscad.com", "OpenSCAD/openscad.exe"],
    )
    if oscad is None:
        pytest.skip("OpenSCAD not installed")

    import trimesh
    from backend.app.cad.organic_sdf_builder import build_organic_sdf_link
    from backend.app.physics.topopt_3d import run_simp_3d_link

    scad_path = tmp_path / "classic_link.scad"
    stl_scad = tmp_path / "classic_link_openscad.stl"
    scad_path.write_text(
        "$fn = 48;\n"
        "difference() {\n"
        "  union() {\n"
        "    cylinder(d=36, h=22, center=true);\n"
        "    translate([180, 0, 0]) cylinder(d=28, h=22, center=true);\n"
        "    hull() {\n"
        "      cylinder(d=36, h=22, center=true);\n"
        "      translate([180, 0, 0]) cylinder(d=28, h=22, center=true);\n"
        "    }\n"
        "  }\n"
        "  cylinder(d=12, h=30, center=true);\n"
        "  translate([180, 0, 0]) cylinder(d=10, h=30, center=true);\n"
        "}\n",
        encoding="utf-8",
    )
    proc = subprocess.run(
        [str(oscad), "-o", str(stl_scad), str(scad_path)],
        capture_output=True,
        text=True,
        timeout=90,
    )
    assert proc.returncode == 0 and stl_scad.exists(), f"OpenSCAD failed: {proc.stderr}"

    oscad_mesh = trimesh.load(str(stl_scad), force="mesh")
    assert oscad_mesh.is_watertight and oscad_mesh.volume > 100000.0

    simp = run_simp_3d_link(180.0, 44.0, 32.0, 22.0, load_n=19.62, angular_accel_rad_s2=8.0)
    rf_mesh, stats = build_organic_sdf_link(simp.rho_3d, 180.0, 44.0, 32.0, 22.0)
    assert stats["is_watertight"] and stats["bodies"] == 1
    mass_savings_pct = (1.0 - rf_mesh.volume / oscad_mesh.volume) * 100.0
    print(f"OPENSCAD_VS_ROBOFORGE: OpenSCAD={oscad_mesh.volume/1000:.1f}cm3 vs RoboForge_SIMP3D={rf_mesh.volume/1000:.1f}cm3 (savings={mass_savings_pct:.1f}%)")
    assert mass_savings_pct > 50.0, f"Expected >50% volume savings vs OpenSCAD solid, got {mass_savings_pct:.1f}%"


def test_orcaslicer_cli_accepts_roboforge_simp3d_and_propeller(tmp_path: Path):
    """Real OrcaSlicer CLI imports and exports a RoboForge SIMP 3D organic STL cleanly (0 slicer errors)."""
    orca = _find_exe(
        ["orca-slicer", "orca-slicer.exe"],
        ["OrcaSlicer/orca-slicer.exe"],
    )
    if orca is None:
        pytest.skip("OrcaSlicer not installed")

    from build123d import export_stl

    prop = generate_propeller_part(5.0, 4.3, 3, "naca4412", "conventional", "ccw")
    stl_in = tmp_path / "roboforge_prop_ccw.stl"
    export_stl(prop, str(stl_in), tolerance=0.09, angular_tolerance=0.14)

    out_3mf = tmp_path / "orcaslicer_verified.3mf"
    proc = subprocess.run(
        [str(orca), "--export-3mf", str(out_3mf), str(stl_in)],
        capture_output=True,
        text=True,
        timeout=90,
    )
    assert proc.returncode == 0 and out_3mf.exists() and out_3mf.stat().st_size > 1000, (
        f"OrcaSlicer CLI failed:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}"
    )
    print(f"ORCASLICER_OK: exported {out_3mf.name} ({out_3mf.stat().st_size} bytes)")

